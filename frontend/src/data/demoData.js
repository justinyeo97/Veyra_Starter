function id(prefix, index) {
  return `${prefix}-${1001 + index}`
}

function timestamp(daysAgo, today) {
  const date = new Date(`${today}T10:30:00`)
  date.setTime(date.getTime() - daysAgo * 86400000)
  return date.toISOString()
}

function buildHistory(sneaker, saleDates, today) {
  const target = INVENTORY_STATUSES.indexOf(sneaker.status)
  const purchased = addDays(today, -sneaker.purchased)
  const listed = sneaker.listed === null ? null : addDays(today, -sneaker.listed)
  const steps = [
    { status: 'Purchased', date: purchased, note: `Bought ${sneaker.stock} at ${sneaker.purchasePrice} each.` },
    { status: 'Cleaning', date: addDays(purchased, 1), note: 'Inspected and sent for cleaning.' },
    { status: 'Ready to List', date: addDays(purchased, 3), note: 'Photographed and ready to list.' },
    { status: 'Listed', date: listed || addDays(purchased, 4), note: `Listed at ${sneaker.listingPrice}.` },
    { status: 'Sold', date: saleDates[saleDates.length - 1] || today, note: 'Last pair sold.' },
    { status: 'Shipped', date: addDays(saleDates[saleDates.length - 1] || today, 1), note: 'Handed to the courier.' },
  ]
  return steps.slice(0, target + 1).map((step, index) => ({
    id: `${index + 1}`,
    status: step.status,
    date: `${step.date}T${String(9 + index).padStart(2, '0')}:00:00`,
    note: step.note,
  }))
}

